#!/usr/bin/env bash
set -euo pipefail

DYN_DIR="${KANJI_DYN_DIR:-/var/lib/ii-sddm-kanji}"
THEME_CONF="$DYN_DIR/theme.conf"
WALL_DEST="$DYN_DIR/wall.jpg"
STATE_WALL="$HOME/.local/state/quickshell/user/generated/wallpaper/path.txt"
COLORS_JSON="${KANJI_COLORS_JSON:-$HOME/.local/state/quickshell/user/generated/colors.json}"
MONITOR_MAP="$HOME/.config/illogical-impulse/monitor-wallpapers.json"
CONFIG_JSON="$HOME/.config/illogical-impulse/config.json"

if [[ ! -d "$DYN_DIR" || ! -w "$DYN_DIR" ]]; then
  echo "Kanji SDDM sync: $DYN_DIR is missing or not writable" >&2
  exit 1
fi

TMP_WALL="$DYN_DIR/.wall.$$.jpg"
TMP_CONF="$DYN_DIR/.theme.conf.$$"
trap 'rm -f "$TMP_WALL" "$TMP_CONF"' EXIT

# Let the file that triggered this service finish being written.
sleep 0.3

WALL=""
if [[ -f "$MONITOR_MAP" ]] && command -v jq >/dev/null 2>&1; then
  WALL=$(jq -r '."eDP-1" // empty' "$MONITOR_MAP" 2>/dev/null || true)
fi
if [[ -z "$WALL" || ! -f "$WALL" ]]; then
  if [[ -f "$STATE_WALL" ]]; then
    WALL=$(<"$STATE_WALL")
  fi
fi
if [[ -z "$WALL" || ! -f "$WALL" ]]; then
  if [[ -f "$CONFIG_JSON" ]] && command -v jq >/dev/null 2>&1; then
    WALL=$(jq -r '.background.wallpaperPath // empty' "$CONFIG_JSON" 2>/dev/null || true)
  fi
fi
if [[ -z "$WALL" || ! -f "$WALL" ]]; then
  echo "Kanji SDDM sync: no readable wallpaper found" >&2
  exit 0
fi

get_color() {
  local key="$1" fallback="$2" val=""
  if [[ -f "$COLORS_JSON" ]] && command -v jq >/dev/null 2>&1; then
    val=$(jq -r --arg k "$key" '.[$k] // empty' "$COLORS_JSON" 2>/dev/null || true)
  fi
  if [[ "$val" =~ ^#[0-9A-Fa-f]{6}$ ]]; then
    printf '%s' "$val"
  else
    printf '%s' "$fallback"
  fi
}

lum() {
  local h="${1#\#}" r g b
  r=$((16#${h:0:2}))
  g=$((16#${h:2:2}))
  b=$((16#${h:4:2}))
  echo $(( (2126 * r + 7152 * g + 722 * b) / 10000 ))
}

pick_light() {
  if (( $(lum "$1") >= $(lum "$2") )); then printf '%s' "$1"; else printf '%s' "$2"; fi
}

pick_dark() {
  if (( $(lum "$1") <= $(lum "$2") )); then printf '%s' "$1"; else printf '%s' "$2"; fi
}

# Kanji is a dark login screen. Pick the lighter/darker member of each
# Matugen pair so the theme stays readable in both light and dark mode.
PAPER=$(pick_light "$(get_color primary "#B0CDBC")" "$(get_color on_primary "#1C3529")")
PAPER_DIM=$(pick_light "$(get_color secondary "#BEC9C1")" "$(get_color on_secondary "#29332D")")
INK=$(pick_dark "$(get_color surface "#121413")" "$(get_color inverse_surface "#E3E2E0")")
INK_SOFT=$(pick_dark "$(get_color surface_container "#1F201F")" "$(get_color inverse_surface "#E3E2E0")")
ACCENT=$(pick_light "$(get_color error "#FFB4AB")" "$(get_color error_container "#93000A")")

# Normalize the current wallpaper to a 1920x1080 JPEG in the SDDM-readable dir.
if command -v magick >/dev/null 2>&1; then
  magick "$WALL" -resize 1920x1080^ -gravity center -extent 1920x1080 -quality 92 "$TMP_WALL"
elif command -v convert >/dev/null 2>&1; then
  convert "$WALL" -resize 1920x1080^ -gravity center -extent 1920x1080 -quality 92 "$TMP_WALL"
else
  cp -f "$WALL" "$TMP_WALL"
fi

cat > "$TMP_CONF" <<EOF
[General]
# Generated by ii-sddm-kanji sync.sh — do not edit by hand.
background=backgrounds/wall.jpg
blurAmount=0.06
tintAmount=0.20
paperColor=$PAPER
paperDimColor=$PAPER_DIM
inkColor=$INK
inkSoftColor=$INK_SOFT
accentColor=$ACCENT
uiScale=1.0
panelWidth=560
panelPosition=left
panelMargin=88
fontFamily=JetBrainsMono Nerd Font
timeFormat=HH:mm
dateFormat=dddd · d MMMM yyyy
userLabel=USER
passwordLabel=PASSWORD
loginText=ENTER
errorMessage=ACCESS DENIED
EOF

mv -f "$TMP_WALL" "$WALL_DEST"
mv -f "$TMP_CONF" "$THEME_CONF"
chmod 644 "$THEME_CONF" "$WALL_DEST"
